"""Builds index.html (the stand-alone page for GitHub Pages) from page.html (the claude.ai version).

claude.ai wraps page.html in its own <html>/<head>/<body> and a small reset when publishing;
this script adds the same wrapper so the page also works on any ordinary web host.
Run: python tools/build_site.py
"""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
src = open(os.path.join(ROOT, "page.html"), encoding="utf-8").read()

# everything up to the end of the first <style> block belongs in <head>
cut = src.index("</style>") + len("</style>")
head, body = src[:cut], src[cut:].lstrip("\n")
head = "\n".join(line for line in head.split("\n") if 'name="claude:' not in line)

page = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="description" content="Łagi: pixel art, mods and house rules for strategy games, board games and tabletop RPGs.">
<link rel="icon" href="img/av-knight.png">
<!-- Link previews (Discord, BGG, Reddit, Facebook...): the card is drawn by tools/og_card.py -->
<meta property="og:type" content="website">
<meta property="og:url" content="https://lagi7.github.io/">
<meta property="og:site_name" content="Łagi">
<meta property="og:title" content="Łagi: amalgamator of sprites, tailor of rules">
<meta property="og:description" content="Pixel art, mods and house rules for strategy games, board games and tabletop RPGs.">
<meta property="og:image" content="https://lagi7.github.io/img/og-card.png">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:image:alt" content="A pixel-art knight and a gas mask in gold rings beside the name Łagi">
<meta name="twitter:card" content="summary_large_image">
<meta name="theme-color" content="#e3c06d">
<!-- Generated by tools/build_site.py from page.html. Edit page.html, then rebuild. -->
<style>
/* The same small reset claude.ai puts around the page */
:root { padding-top: env(safe-area-inset-top, 0px); padding-bottom: env(safe-area-inset-bottom, 0px); }
body { margin: 0; }
img { max-width: 100%%; }
[hidden] { display: none !important; }
</style>
%s
</head>
<body>
%s</body>
</html>
""" % (head, body)
open(os.path.join(ROOT, "index.html"), "w", encoding="utf-8", newline="\n").write(page)
print("wrote index.html", len(page), "bytes")
